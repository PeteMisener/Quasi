"""Fail-closed comparison of Quasi phase-7 RDD vs ACTUAL R rdrobust output.

Requires independent R reference generated by phase7_rd_external_reference.R.
Never runs a synthetic fallback or fabricates missing reference output.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
import quasi
from validation.rdd_fixture_contract import load_phase7_fixture
from validation.rdd_reference_contract import validate_r_reference


def compare(fixture: Path, reference: Path, output: Path, atol=1e-5, se_rtol=0.08):
    if not reference.is_file():
        raise FileNotFoundError('Authentic R rdrobust result unavailable; parity gate BLOCKED')
    data, fixture_hash = load_phase7_fixture(fixture)
    ref = pd.read_csv(reference)
    validate_r_reference(ref, fixture_hash)
    result={'status':'pending_comparison', 'reference_certified': False,
            'reference_version':sorted(ref.reference_version.unique().tolist()),
            'reference_generator': 'validation/r/phase7_rd_external_reference.R',
            'parameters': {'h': 1.15, 'b': 1.35, 'p': 1, 'q': 2, 'kernel': 'tri', 'vce': 'hc0'},
            'fixture_sha256':fixture_hash,
            'comparisons': []}
    passed=True
    for design in ('sharp','fuzzy'):
        for method in ('conventional','bias_corrected'):
            params={'inference':method}
            if method=='bias_corrected':
                params['bias_bandwidth']=1.35
            model=(quasi.FuzzyRDD if design=='fuzzy' else quasi.SharpRDD)
            est=model(data=data,outcome='y',running_var='x',cutoff=0.0,bandwidth=1.15,
                      treatment='d' if design=='fuzzy' else None,**params).fit()
            row=ref.loc[(ref.design==design)&(ref.method==method)]
            if len(row)!=1:
                raise ValueError('Nonunique reference row')
            row=row.iloc[0]
            pt_ok=bool(np.isclose(est.estimate,row.estimate,rtol=0,atol=atol))
            se_ok=bool(np.isclose(est.se,row.se,rtol=se_rtol,atol=1e-7))
            passed &= pt_ok and se_ok
            result['comparisons'].append(dict(design=design,method=method,
                quasi_estimate=est.estimate,r_estimate=float(row.estimate),
                quasi_se=est.se,r_se=float(row.se),point_pass=pt_ok,se_pass=se_ok))
    result['status']='numerically_passed_unreviewed' if passed else 'FAILED_NUMERICAL_PARITY'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(result,indent=2)+'\n')
    if not passed:
        raise SystemExit('Phase 7 reference disagreement; examine variance estimators and bandwidth conventions')
    print('Numerical comparison passed; independent statistical certification still required')


if __name__=='__main__':
    ap=argparse.ArgumentParser()
    ap.add_argument('--fixture',type=Path,default=Path('validation/fixtures/rdd_phase7_fixed.csv'))
    ap.add_argument('--reference',type=Path,required=True)
    ap.add_argument('--output',type=Path,default=Path('phase7_rdd_comparison.json'))
    args=ap.parse_args()
    compare(args.fixture,args.reference,args.output)
