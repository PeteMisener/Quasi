"""Fail-closed comparison of frozen Phase-10B input with an *executed* R synthdid run.

Generate the fixture once in the repository; run the official R implementation
externally, then compare its independently computed point estimate and weights.
No reference is generated by this Python module.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

from quasi.synth.sdid import _sdid_weights, _sdid_effect

FIXTURES = Path(__file__).parent / 'fixtures'
FILE = FIXTURES / 'sdid_phase10b_panel.csv'
MANIFEST = FIXTURES / 'sdid_phase10b_panel.json'


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fixture_inputs():
    manifest = json.loads(MANIFEST.read_text())
    actual = digest(FILE.read_bytes())
    if actual != manifest['sha256']:
        raise ValueError('SDiD fixture checksum mismatch; reference comparison BLOCKED')
    if manifest['design'] != 'one_treated_unit_single_onset':
        raise ValueError('Unexpected SDiD fixture design')
    df = pd.read_csv(FILE)
    treated_id = manifest['treated_unit']
    time_labels = sorted(df.time.unique())
    donors = sorted(set(df.unit)-{treated_id})
    if len(df) != len(time_labels)*(len(donors)+1):
        raise ValueError('SDiD benchmark panel must be complete and balanced')
    if df[['unit','time']].duplicated().any() or df[['unit','time','y']].isna().any().any():
        raise ValueError('SDiD benchmark has duplicate or nonfinite rows')
    pivot = df.pivot(index='unit',columns='time',values='y').loc[[*donors,treated_id],time_labels]
    Y = pivot.to_numpy(dtype=float)
    split = time_labels.index(manifest['intervention_time'])
    if not np.isfinite(Y).all() or split < 2 or split >= len(time_labels):
        raise ValueError('Invalid SDiD benchmark data')
    return manifest,Y,split


def compare(reference: Path, *, point_atol: float = 0.001,
            weight_atol: float = 0.01) -> dict:
    manifest,Y,k=fixture_inputs()
    ext = json.loads(reference.read_text())
    for field, expected in {
        'method': 'R_synthdid_estimate',
        'fixture_sha256': manifest['sha256'],
        'design': manifest['design'],
        'sparsify': 'none',
        'omega_intercept': True,
        'lambda_intercept': True,
        'reference_execution': 'R_synthdid',
    }.items():
        if ext.get(field) != expected:
            raise ValueError(f'Independent reference metadata mismatch: {field}')
    if not isinstance(ext.get('package_version'),str) or not ext['package_version']:
        raise ValueError('Independent reference has no synthdid version')
    def validate_vector(name,length):
        val=np.asarray(ext.get(name,[]),dtype=float)
        if val.shape!=(length,) or not np.isfinite(val).all() or min(val)<-1e-8 or abs(val.sum()-1)>1e-6:
            raise ValueError(f'Invalid reference {name} weights')
        return val
    w=validate_vector('omega',Y.shape[0]-1)
    lam=validate_vector('lambda',k)
    ext_att=float(ext['estimate'])
    if not np.isfinite(ext_att):
        raise ValueError('Invalid external ATT')
    if abs(_sdid_effect(Y[-1],Y[:-1],k,w,lam)-ext_att)>1e-8:
        raise ValueError('Reference ATT does not agree with its own weights')
    ours_w,ours_l,details=_sdid_weights(Y[-1],Y[:-1],k)
    ours_att=_sdid_effect(Y[-1],Y[:-1],k,ours_w,ours_l)
    diffs={'att':abs(ours_att-ext_att),
           'omega':float(np.max(np.abs(ours_w-w))),
           'lambda':float(np.max(np.abs(ours_l-lam)))}
    passed = bool(diffs['att']<=point_atol and diffs['omega']<=weight_atol and diffs['lambda']<=weight_atol)
    return {'status':'numeric_candidate_pass' if passed else 'numeric_candidate_fail',
            'statistical_certified':False,'reference_package':'synthdid',
            'reference_version':ext['package_version'],
            'reference_fixture_sha256':manifest['sha256'],
            'absolute_differences':diffs,'tolerances':{'att':point_atol,'weights':weight_atol},
            'quasi_att':ours_att,'r_att':ext_att,
            'weight_metadata':details}


def main():
    p=argparse.ArgumentParser()
    p.add_argument('reference',type=Path)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    if not args.reference.exists():
        p.error('Actual independently generated R reference JSON is REQUIRED')
    evidence=compare(args.reference)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(json.dumps(evidence,indent=2,allow_nan=False)+'\n')
    if evidence['status']!='numeric_candidate_pass':
        raise SystemExit('SDiD reference comparison FAILED')
    print('SDiD numerical candidate check PASSED; statistical certification still pending')


if __name__=='__main__':
    main()
